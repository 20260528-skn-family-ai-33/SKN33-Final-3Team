  await page.fill('#fi-name', '홍길동')
  await page.click('button:has-text("아이디 찾기")')
  await page.waitForTimeout(300)
  await page.waitForTimeout(300)
  check('LG08 가입 계정 목록(마스킹)', (await text()).includes('ho***@example.com'))
