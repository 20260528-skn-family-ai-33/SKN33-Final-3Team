// npm run build 후 미리보기 서버에서 실행: node tests/admin-inbox.cjs [URL]
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const BASE = process.argv[2] || 'http://127.0.0.1:4173'

;(async () => {
  const browser = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {})
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
    const errors = []
    page.on('pageerror', e => errors.push(String(e)))
    const go = async path => { await page.goto(`${BASE}/#${path}`, { waitUntil: 'domcontentloaded' }); await page.waitForTimeout(150) }
    const click = async name => { await page.getByRole('link', { name, exact: true }).click(); await page.waitForTimeout(100) }
    const title = async expected => { await page.waitForFunction(value => document.querySelector('h2')?.textContent === value, expected) }
    const inboxActive = async () => assert.equal(await page.locator('.side [aria-current="page"]').innerText(), '알림함')
    await go('/login')
    await page.fill('#login-email', 'admin@example.com')
    await page.fill('#login-password', 'admin1234!')
    await page.locator('button[type=submit]').click()
    await page.waitForURL('**/#/admin', { waitUntil: 'domcontentloaded' })
    await page.locator('.side').waitFor()
    assert.deepEqual(await page.locator('.side a').allTextContents(), ['운영 현황', '알림함', '회원·권한', '키워드·분류 체계', '처리 이력·운영 설정'])
    for (const [category, id] of [['전체', 'BS33'], ['데이터', 'BS35'], ['리포트', 'BS37'], ['회원관리', 'BS39']]) {
      await go('/admin')
      await click(category)
      await page.locator('section.card').filter({ has: page.locator('p.t2', { hasText: /^알림$/ }) }).getByRole('link', { name: '상세보기', exact: true }).click()
      await page.waitForURL(`**/#/admin/inbox/${id}`)
      await title('관리자 알림')
      await inboxActive()
      assert.equal(await page.locator('.chips').nth(1).locator('.on').innerText(), category)
    }
    await click('알림함')
    await title('관리자 알림')
    assert.equal(await page.locator('.tr').count(), 3)
    await click('데이터 수집 이력')
    await title('데이터 수집 이력')
    assert.equal(await page.locator('.tr .tag.ok').count(), 2)
    assert.equal(await page.locator('.tr .tag.red').count(), 1)
    assert.equal(await page.getByRole('link', { name: '재시도', exact: true }).count(), 1)
    for (const [name, expected] of [['KOTRA', '기사 수집 상세'], ['ECOS', '환율 수집 상세']]) {
      await page.locator('.tr').filter({ hasText: name }).getByRole('link', { name: '상세', exact: true }).click()
      await title(expected)
      await inboxActive()
      await click('목록 / 뒤로')
      await title('데이터 수집 이력')
    }
    if (process.env.SCREENSHOT) await page.screenshot({ path: process.env.SCREENSHOT, fullPage: true })
    await page.locator('.tr').filter({ hasText: '관세청' }).getByRole('link', { name: '상세', exact: true }).click()
    await click('실행 로그')
    assert.match(await page.getByRole('log').innerText(), /Process finished with exit code 1/)
    await click('실패 범위 재수집')
    assert.equal(await page.getByRole('dialog').count(), 1)
    await page.getByRole('dialog').getByRole('link', { name: '취소', exact: true }).click()
    await title('수출 통계 수집 상세')
    await click('데이터 수집 이력')
    await click('재시도')
    await page.getByRole('dialog').getByRole('link', { name: '재수집 시작', exact: true }).click()
    await title('재수집 진행 중')
    await inboxActive()
    await click('실패 상태 보기')
    assert.match(await page.locator('body').innerText(), /재시도 실패 · 공개 보류/)
    await click('다시 시도')
    await page.getByRole('dialog').getByRole('link', { name: '재수집 시작', exact: true }).click()
    await click('완료 상태 보기')
    assert.match(await page.locator('body').innerText(), /재수집과 검증을 완료했습니다/)
    await click('목록 / 뒤로')
    await title('데이터 수집 이력')
    await click('회원 알림 전달 내역')
    await page.locator('.tr').first().getByRole('link', { name: '상세', exact: true }).click()
    await title('회원 리포트 알림 전달 상세')
    await inboxActive()
    await click('수신 설정')
    await click('약관 응답 이력')
    await title('약관 응답 이력')
    await click('회원 알림 전달 내역')
    await click('급증 판정 기준')
    await title('기사량 알림 판정 기준')
    await click('데이터 수집 이력')
    await click('수집 현황 보기')
    await title('데이터 수집 현황')
    await inboxActive()
    assert.ok(page.url().includes('/admin/inbox/BS64'))
    assert.equal(await page.locator('.chips .on').innerText(), '데이터 수집 이력')
    await click('수집 이력 보기')
    await inboxActive()
    for (const path of ['/admin/ops/BS33', '/admin/data/BS64', '/admin/data/BS68', '/admin/delivery/BS149']) {
      await go(path)
      await inboxActive()
    }
    await click('회원·권한')
    assert.ok(!(await page.locator('.chips').innerText()).includes('검색 결과'))
    await page.fill('#member-q', '이서연')
    await page.getByRole('button', { name: '검색', exact: true }).click()
    await page.waitForURL('**/BS49?*')
    await title('회원 검색 결과')
    assert.match(await page.locator('.tr').innerText(), /editor@example.com/)
    assert.equal(await page.locator('#member-q').inputValue(), '이서연')
    assert.ok(!(await page.locator('.chips').innerText()).includes('검색 결과'))
    await page.fill('#member-q', 'no-such-member')
    await page.getByRole('button', { name: '검색', exact: true }).click()
    await page.waitForTimeout(150)
    assert.equal(await page.locator('.tr').count(), 0)
    await page.locator('button.bell').click()
    await page.waitForURL('**/#/admin/inbox/BS33')
    await title('관리자 알림')
    assert.deepEqual(errors, [])
    console.log('PASS 관리자 메뉴·알림 유형·수집 이력·로그·재시도 취소/실패/성공·전달 상세·기존 URL·회원 검색·머리글 알림')
  } finally {
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
