// SQLite/fakeredis 전용 서버에서만 실행. fixture: RecoveryKeywordAdminTest + built frontend.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const base = process.argv[2] || 'http://127.0.0.1:8879'
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('local fixture server only')
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const page = await browser.newPage({viewport:{width:1440,height:1000}})
  const errors=[]; page.on('pageerror',e=>errors.push(e.message))
  page.setDefaultTimeout(10000)
  const go = route => page.goto(`${base}/#${route}`)
  const name = `독립 분류 ${Date.now()}`, renamed = name+' 수정'
  let assignments=0, mutations=0, creations=0
  page.on('request',r=>{
    if(r.method()==='PATCH' && r.url().includes('/keyword-topics/review')) assignments++
    if(['PATCH','DELETE'].includes(r.method()) && r.url().includes('/keyword-majors')) mutations++
    if(r.method()==='POST' && r.url().includes('/keyword-categories')) creations++
  })
  try {
    await go('/login')
    await page.locator('#login-email').fill('alice@example.org')
    await page.locator('#login-password').fill('Sample!123')
    await page.locator('button[type=submit]').click()
    await page.locator('.side').waitFor()
    await go('/admin/keywords?kw=검수키워드')
    await page.locator('#keyword-major').selectOption('무역·통상')
    await page.locator('#keyword-minor').selectOption('1')
    await page.locator('#keyword-reason').fill('확인창 검증')
    await page.getByRole('button',{name:'분야 지정·변경',exact:true}).click()
    await page.getByRole('dialog').waitFor()
    assert.equal(assignments,0)
    await page.getByRole('dialog').getByRole('button',{name:'취소',exact:true}).click()
    assert.equal(assignments,0)
    await page.getByRole('button',{name:'분야 지정·변경',exact:true}).click()
    await page.getByRole('dialog').getByRole('button',{name:'확인',exact:true}).click()
    await page.getByRole('dialog').waitFor({state:'hidden'})
    assert.equal(assignments,1)
    console.log('PASS 지정 확인 전·취소 시 저장 없음, 확인 후 저장')

    await page.getByRole('button',{name:'+ 대분류 추가',exact:true}).click()
    await page.getByLabel('새 대분류',{exact:true}).fill(name)
    await page.getByRole('button',{name:'대분류 저장',exact:true}).click()
    await page.getByRole('dialog',{name:'대분류 추가 확인'}).waitFor()
    assert.equal(creations,0)
    assert.equal(await page.getByRole('dialog').getByRole('button',{name:'확인하고 추가',exact:true}).isDisabled(),true)
    await page.getByRole('dialog').getByRole('button',{name:'취소',exact:true}).click()
    assert.equal(creations,0)
    await page.getByRole('button',{name:'대분류 저장',exact:true}).click()
    await page.locator('#category-create-reason').fill('신규 분야 필요')
    await page.getByRole('dialog').getByRole('button',{name:'확인하고 추가',exact:true}).click()
    await page.getByLabel('새 대분류',{exact:true}).waitFor({state:'hidden'})
    assert.equal(creations,1)
    console.log('PASS 인라인 대분류 추가: 확인 전·취소 시 저장 없음, 사유 입력 후 저장')
    assert.equal(await page.locator('#keyword-major').inputValue(),name)
    await go('/admin/keywords/fields')
    const row = n => page.locator('.between').filter({has:page.getByText(n,{exact:true})})
    await row(name).getByRole('button',{name:'이름 수정',exact:true}).click()
    await page.locator('#major-rename').fill(renamed)
    await page.locator('#major-reason').fill('오타 수정')
    await page.getByRole('dialog').getByRole('button',{name:'취소',exact:true}).click()
    assert.equal(mutations,0)
    await row(name).getByRole('button',{name:'이름 수정',exact:true}).click()
    await page.locator('#major-rename').fill(renamed)
    await page.locator('#major-reason').fill('오타 수정')
    await page.getByRole('dialog').getByRole('button',{name:'확인하고 저장',exact:true}).click()
    await row(renamed).waitFor()
    assert.equal(await page.getByText(name,{exact:true}).count(),0)
    await page.reload()
    await row(renamed).getByRole('button',{name:'삭제',exact:true}).click()
    await page.getByRole('dialog').getByRole('button',{name:'취소',exact:true}).click()
    assert.equal(mutations,1)
    await row(renamed).getByRole('button',{name:'삭제',exact:true}).click()
    await page.locator('#major-reason').fill('미사용 정리')
    await page.getByRole('dialog').getByRole('button',{name:'확인하고 삭제',exact:true}).click()
    await page.getByRole('dialog').waitFor({state:'hidden'})
    await page.getByRole('button',{name:'새 분야 만들기',exact:true}).waitFor()
    assert.equal(await page.getByText(renamed,{exact:true}).count(),0)
    assert.equal(mutations,2)
    await go('/admin/keywords?kw=검수키워드')
    await page.locator('#keyword-major').waitFor()
    assert.equal(await page.locator('#keyword-major option').filter({hasText:renamed}).count(),0)
    console.log('PASS 독립 저장 → 이름 수정·삭제 확인 → 새로고침·선택 목록 유지')
    assert.deepEqual(errors,[])
  } catch (error) { console.error(await page.locator('body').innerText()); throw error }
  finally { await browser.close() }
})().catch(e=>{console.error(e);process.exitCode=1})
