// 전용 SQLite/fakeredis 테스트 서버에서만 실행한다. 운영 서버 사용 금지.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = process.argv[2] || 'http://127.0.0.1:8876'
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('localhost test server only')

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('response', async r => { if (r.status() >= 400 && r.url().includes('/api/v1/')) console.log('HTTP', r.status(), new URL(r.url()).pathname) })
  page.setDefaultTimeout(15000)
  const out = path.resolve(__dirname, '../../tmp/backend_build/recovery-admin-browser')
  fs.mkdirSync(out, { recursive: true })
  const go = route => page.goto(`${base}/#${route}`)
  try {
    await go('/find-id')
    await page.locator('#fi-name').fill('홍길동')
    await page.locator('#fi-email').fill('alice@example.org')
    await page.getByRole('heading', { name: '가입 여부 확인', exact: true }).waitFor()
    await page.getByRole('button', { name: '가입 여부 확인', exact: true }).click()
    await page.getByRole('dialog').getByText('가입된 계정입니다.', { exact: true }).waitFor()
    await page.getByRole('dialog').getByRole('button', { name: '확인', exact: true }).click()
    await page.locator('#fi-name').fill('다른이름')
    await page.getByRole('button', { name: '가입 여부 확인', exact: true }).click()
    await page.getByRole('dialog').getByText('해당정보로 가입된 계정이 없습니다', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(out, 'account-confirmation.png'), fullPage: true })
    console.log('PASS 이름·이메일 일치/불일치 팝업')

    await go('/login')
    await page.locator('#login-email').fill('alice@example.org')
    await page.locator('#login-password').fill('Sample!123')
    await page.locator('button[type=submit]').click()
    await page.locator('.side').waitFor()
    await go('/admin/members/BS48?user_id=1')
    await page.getByRole('heading', { name: '회원 상세', exact: true }).waitFor()
    for (const name of ['관심정보', '리포트 구독', '알림 설정']) await page.getByRole('heading', { name, exact: true }).waitFor()
    const detail = page.locator('section.card').filter({ has: page.getByRole('heading', { name: '회원 상세', exact: true }) }).first()
    assert.match(await detail.innerText(), /\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}/)
    assert.doesNotMatch(await detail.innerText(), /T\d{2}:\d{2}/)
    await page.screenshot({ path: path.join(out, 'member-detail.png'), fullPage: true })
    console.log('PASS 회원 관심·구독·알림 및 KST 표시')

    await go('/admin/keywords')
    await page.getByRole('button', { name: /검수키워드/ }).click()
    await page.getByRole('heading', { name: '검수키워드', exact: true }).waitFor()
    await page.getByText('실제 근거 기사', { exact: false }).waitFor()
    await page.locator('#keyword-major').selectOption('무역·통상')
    await page.locator('#keyword-minor').selectOption('1')
    await page.locator('#keyword-reason').fill('브라우저에서 기사 근거 확인')
    await page.getByRole('button', { name: '분야 지정·변경', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: '확인', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await go('/admin/keywords?status=REVIEWED&kw=검수키워드')
    await page.getByRole('button', { name: /검수키워드/ }).waitFor()
    await page.reload()
    await page.locator('#keyword-minor').waitFor()
    assert.equal(await page.locator('#keyword-minor').inputValue(), '1')
    await page.locator('#keyword-minor').selectOption('2')
    await page.locator('#keyword-reason').fill('분야 변경 검증')
    await page.getByRole('button', { name: '분야 지정·변경', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: '확인', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.locator('#keyword-minor').waitFor()
    assert.equal(await page.locator('#keyword-minor').inputValue(), '2')
    await page.screenshot({ path: path.join(out, 'keyword-review.png'), fullPage: true })
    await go('/admin/keywords/history')
    await page.getByText('분야 변경 검증', { exact: true }).waitFor()
    await page.getByRole('button', { name: '상세', exact: true }).first().click()
    await page.getByRole('dialog').getByRole('heading', { name: '처리 이력 상세', exact: true }).waitFor()
    await page.getByRole('dialog').getByText('분야 변경 검증', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(out, 'keyword-history.png'), fullPage: true })
    console.log('PASS 키워드 목록·분류 지정/변경·새로고침 유지·처리 이력')

    await go('/admin/keywords/fields')
    await page.getByText('기본 대분류 8개 · 서버에 저장된 중분류 23개', { exact: true }).waitFor()
    await page.getByRole('button', { name: '새 분야 만들기', exact: true }).click()
    await page.locator('#category-major').fill('운영 분류')
    await page.locator('#category-minor').fill('브라우저 분야')
    await page.locator('#category-reason').fill('새 분야 저장 검증')
    await page.getByRole('button', { name: '확인하고 저장', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.getByText('운영 분류 › 브라우저 분야', { exact: true }).waitFor()
    console.log('PASS 대분류 8개·관리자 분야 생성')

    const createdField = page.locator('.between').filter({ has: page.getByText('운영 분류 › 브라우저 분야', { exact: true }) })
    await createdField.getByRole('button', { name: '이름 수정', exact: true }).click()
    assert.equal(await page.getByRole('dialog').getByRole('button', { name: '삭제', exact: true }).count(), 0)
    await page.locator('#category-minor').fill('변경 분야')
    await page.locator('#category-reason').fill('분야 이름 변경 검증')
    await page.getByRole('dialog').getByRole('button', { name: '확인하고 저장', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.getByText('운영 분류 › 변경 분야', { exact: true }).waitFor()
    console.log('PASS 분야 이름 변경·삭제 기능 제외')

    await go('/find-password')
    await page.locator('#fp-name').fill('홍길동')
    await page.locator('#fp-email').fill('alice@example.org')
    await page.getByRole('button', { name: '임시 비밀번호 받기', exact: true }).click()
    await page.getByRole('dialog').getByText(/입력한 이메일로 임시 비밀번호를 발송했습니다/).waitFor()
    console.log('PASS 임시 비밀번호 발급 성공 안내 (메일 전송은 모의 처리)')
    assert.deepEqual(errors, [])
  } catch (e) {
    await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true })
    console.error(await page.locator('main').innerText().catch(() => '화면 읽기 실패'))
    throw e
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
