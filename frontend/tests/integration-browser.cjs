// Existing screens + real local API, MySQL, Redis and worker. No route mocks.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path')
async function main() {
  const base = process.argv[2] || 'http://127.0.0.1:5173'
  if (!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(base)) throw new Error('Synthetic test accounts: localhost only')
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : { channel: 'chrome' }) })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
  const page = await context.newPage(); page.setDefaultTimeout(25000)
  const errors = [], checks = []
  page.on('pageerror', e => errors.push(e.message))
  const out = path.resolve(__dirname, '../../tmp/browser-original'); fs.mkdirSync(out, { recursive: true })
  const ok = s => { checks.push(s); console.log('PASS '+s) }
  const email = `original-${Date.now()}@example.org`, password = 'Original!123'
  const go = url => page.goto(base+'/#'+url)
  try {
    await go('/signup')
    await page.locator('#su-name').fill('기존화면 검증')
    await page.locator('#su-email').fill(email)
    await page.locator('#su-password').fill(password)
    await page.locator('#su-confirm').fill(password)
    for (const label of ['만 14세 이상', '서비스 이용약관', '개인정보 수집·이용']) await page.locator('label.opt', { hasText: label }).click()
    await page.getByRole('button', { name: '회원가입하고 관심사 설정하기' }).click()
    await page.waitForURL('**/#/onboarding')
    await page.getByRole('heading', { name: '관심 품목을 선택해 주세요' }).waitFor()
    ok('기존 가입 화면으로 회원가입·세션 발급')
    await page.getByLabel('품목 검색', { exact: true }).fill('3304')
    await page.getByRole('option').filter({ hasText: '3304' }).click()
    await page.getByRole('checkbox', { name: /330499/ }).locator('..').click()
    await page.getByRole('link', { name: '다음: 국가 선택' }).click()
    await page.getByRole('checkbox', { name: '미국', exact: true }).locator('..').click()
    await page.getByRole('link', { name: '다음: 완료 확인' }).click()
    await page.reload()
    await page.getByText('HS 330499', { exact: true }).waitFor()
    await page.getByText('미국', { exact: true }).waitFor()
    await page.getByRole('button', { name: '완료하고 시작하기' }).click()
    await page.waitForURL('**/#/?view=interest')
    await page.getByRole('heading', { name: '내 관심 시장 수출입 현황' }).waitFor()
    await page.getByText('330499', { exact: true }).first().waitFor()
    await page.screenshot({ path: path.join(out, 'dashboard.png'), fullPage: true })
    ok('기존 3단계 관심사 등록·실제 통계 카드')
    await page.reload(); await page.getByRole('heading', { name: '내 관심 시장 수출입 현황' }).waitFor()
    ok('새로고침 세션·CSRF·관심사 복원')
    await go('/account/interests')
    await page.getByRole('button', { name: /기초화장품 삭제/ }).waitFor()
    ok('기존 관심정보 화면에서 저장값 확인')
    await go('/rank')
    // 국가는 검색형 입력: 이름을 입력한 뒤 목록에서 고른다.
    await page.getByLabel('국가', { exact: true }).click()
    await page.getByLabel('국가', { exact: true }).fill('미국')
    await page.getByRole('option', { name: '미국', exact: true }).click()
    await page.getByRole('button', { name: '순위 조회', exact: true }).click()
    await page.getByText('330499', { exact: true }).waitFor()
    const excel = page.waitForEvent('download')
    await page.getByRole('button', { name: '엑셀 다운로드' }).click()
    await (await excel).saveAs(path.join(out, 'ranking.xlsx'))
    ok('기존 순위 필터·막대·원본 XLSX 다운로드')
    // 관심 범위 순위: 다른 탭에서 관심 품목을 바꾼 것처럼 서버 값만 바꿔(이 탭의 프로필은 330499 하나) 화면이 응답 기준으로 표기하는지 본다.
    const putInterests = codes => page.evaluate(async codes => {
      const me = await (await fetch('/api/v1/users/me')).json()
      const cur = (await (await fetch('/api/v1/users/me/interests')).json()).interests
      const r = await fetch('/api/v1/users/me/interests', { method: 'PUT', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': me.csrf_token },
        body: JSON.stringify({ hs_items: codes.map(hs_code => ({ hs_code, hs_ver: 'HS2022' })), country_codes: cur.country_codes, expected_version: cur.version, landing_page: 'INTERESTED' }) })
      return r.status
    }, codes)
    assert.equal(await putInterests(['330499', '330410']), 200)
    // 순위 응답을 늦춰(가짜 응답 아님) 조회 중에는 AI 버튼이 비활성인지 확인한다.
    await page.route('**/api/v1/trade/rankings**', async route => { await new Promise(r => setTimeout(r, 1500)); await route.continue() })
    await go('/rank?scope=INTERESTED&group_by=HS6')
    await page.locator('.fab[aria-disabled="true"]').waitFor()
    await page.getByRole('heading', { name: '미국 교역 품목 순위' }).waitFor()
    await page.locator('a.fab[href*="analysis?ask"]').waitFor()
    await page.unroute('**/api/v1/trade/rankings**')
    const ask = decodeURIComponent(await page.locator('a.fab').getAttribute('href'))
    for (const part of [/^#\/analysis\?ask=미국 · /, /\(HS 330499\)/, /\(HS 330410\)/, / 수출 기준 교역 품목 순위를 분석해줘$/]) assert.match(ask, part)
    await page.getByText('330499', { exact: true }).first().waitFor()
    const interestExcel = page.waitForEvent('download')
    await page.getByRole('button', { name: '엑셀 다운로드' }).click()
    assert.match((await interestExcel).suggestedFilename(), /^미국_.*_관심품목_품목순위\.xlsx$/)
    // 상위 코드(HS4 3304)를 지정해도 서버는 그 아래 관심 HS6만 집계하므로 AI 질문에는 HS4가 아니라 실제 HS6 목록이 들어가야 한다.
    await go('/rank?scope=INTERESTED&group_by=COUNTRY&product=3304')
    await page.locator('a.fab[href*="analysis?ask"]').waitFor()
    const askHs4 = decodeURIComponent(await page.locator('a.fab').getAttribute('href'))
    for (const part of [/\(HS 330499\)/, /\(HS 330410\)/, / 수출 기준 교역국 순위를 분석해줘$/]) assert.match(askHs4, part)
    assert.doesNotMatch(askHs4, /\(HS 3304\)/)
    assert.equal(await putInterests(['330499']), 200)
    ok('관심 범위 순위: 응답 전 AI 비활성·응답 기준 표·파일명·AI 질문(종류·기준·상위 코드 지정 포함)')
    await go('/articles')
    await page.locator('#ar-q').fill('검증')
    await page.getByRole('button', { name: '기사 검색' }).click()
    // 기사 유형별로 검증한다: 일반·주요이슈는 원문 보기, 단신속보는 상세 펼치기(원문 버튼 없음).
    // "AI에게 물어보기"는 사용하지 않기로 해 화면에 없어야 한다(2026-11-11).
    await page.locator('article').first().waitFor()
    const cards = page.locator('article')
    for (let i = 0; i < await cards.count(); i++) {
      const card = cards.nth(i)
      if (await card.getByText('단신속보', { exact: true }).count()) {
        await card.getByRole('link', { name: '상세 보기' }).click()
        await card.getByRole('link', { name: '접기' }).waitFor()
        assert.equal(await card.getByRole('button', { name: /원문 보기/ }).count(), 0)
        assert.equal(await card.getByRole('link', { name: /AI에게 물어보기/ }).count(), 0)
        await card.getByRole('link', { name: '접기' }).click()
      } else {
        await card.getByRole('button', { name: /원문 보기/ }).waitFor()
        assert.equal(await card.getByRole('link', { name: /AI에게 물어보기/ }).count(), 0)
      }
    }
    ok('기사 탭에 AI에게 물어보기 버튼 없음')
    await go('/account/settings')
    await page.getByRole('switch', { name: '전체 알림 수신' }).click()
    await page.getByRole('checkbox', { name: '위 알림 수신 약관을 확인했으며 동의합니다.' }).locator('..').click()
    await page.getByRole('button', { name: '동의하고 켜기' }).click()
    await page.getByRole('button', { name: '설정 저장' }).click()
    await page.getByRole('status').filter({ hasText: '알림 설정을 저장했습니다.' }).waitFor()
    await page.reload(); await page.getByRole('switch', { name: '전체 알림 수신' }).waitFor()
    assert.equal(await page.getByRole('switch', { name: '전체 알림 수신' }).getAttribute('aria-checked'), 'true')
    ok('기존 약관 모달·동의 기록·알림 설정 복원')
    await go('/account/subscription')
    await page.getByRole('checkbox', { name: /월간/ }).locator('..').click()
    await page.getByRole('button', { name: /저장/, exact: false }).click()
    await page.waitForURL('**/#/account/reports?tab=monthly')
    await page.getByRole('link', { name: '삭제', exact: true }).click()
    await page.getByRole('button', { name: '구독 삭제', exact: true }).click()
    await page.getByText('월간 리포트를 아직 구독하지 않았습니다.', { exact: true }).waitFor()
    ok('기존 구독 설정·삭제 확인 모달')
    await go('/analysis')
    await page.getByRole('button', { name: '새 채팅', exact: true }).click()
    await page.getByRole('button', { name: '선택 채팅방 이름 변경' }).click()
    await page.getByLabel('새 이름').fill('API 연동 검증')
    await page.getByRole('button', { name: '저장', exact: true }).click()
    await page.getByRole('heading', { name: 'API 연동 검증', exact: true }).waitFor()
    ok('기존 채팅방 생성·이름 변경')
    await page.getByLabel('질문 입력').fill('미국 HS330499 2025년 10월부터 12월까지 수출 추이를 보여줘')
    await page.getByRole('button', { name: '전송', exact: true }).click()
    // 품목 확인 선택지는 DB의 HS6 이름(예: '기타 메이크업 및 기초화장품')으로 나온다.
    // 답변은 worker가 만들므로 다음 단계처럼 넉넉히 기다린다.
    await page.getByRole('button', { name: /기초화장품/ }).first().click({ timeout: 90000 })
    await page.getByRole('button', { name: '리포트로 저장', exact: true }).waitFor({ timeout: 90000 })
    await page.getByRole('button', { name: '표로 보기', exact: true }).first().click()
    await page.getByRole('button', { name: '차트로 보기', exact: true }).first().waitFor()
    ok('실제 분석 작업·기존 답변 카드·차트/표 전환')
    await page.getByRole('button', { name: '리포트로 저장', exact: true }).click()
    await page.getByRole('button', { name: '리포트 조건 확인' }).click()
    await page.getByRole('button', { name: '확인한 조건으로 생성' }).click()
    // 리포트 생성 뒤에는 채팅에 머문다. 완료되면 나오는 버튼으로 리포트 화면에 들어간다.
    await page.getByRole('link', { name: '리포트 센터에서 이 리포트 열기' }).first().click({ timeout: 90000 })
    await page.waitForURL('**/#/report?id=*')
    await page.getByRole('button', { name: 'PDF', exact: true }).waitFor({ timeout: 90000 })
    const pdf = page.waitForEvent('download'); await page.getByRole('button', { name: 'PDF', exact: true }).click()
    await (await pdf).saveAs(path.join(out, 'report.pdf'))
    const docx = page.waitForEvent('download'); await page.getByRole('button', { name: 'DOCX', exact: true }).click()
    await (await docx).saveAs(path.join(out, 'report.docx'))
    await page.screenshot({ path: path.join(out, 'report.png'), fullPage: true })
    await page.reload(); await page.getByRole('button', { name: 'PDF', exact: true }).waitFor()
    ok('조건 확인·worker 리포트 생성·기존 리포트 지면·PDF/DOCX·새로고침')
    await go('/admin'); await page.getByText('관리자 권한이 필요한 화면입니다', { exact: true }).waitFor()
    ok('일반 회원 관리자 접근 차단')
    await go('/account/profile')
    await page.getByText(/^\d{4}-\d{2}-\d{2} 동의$/).nth(1).waitFor()
    assert.equal(await page.getByRole('switch').count(), 0)
    ok('회원정보에 가입 약관 동의 날짜 표시')
    await page.getByRole('button', { name: '로그아웃', exact: true }).click(); await page.waitForURL('**/#/login')
    await page.locator('#login-email').fill(email); await page.locator('#login-password').fill(password)
    await page.getByRole('button', { name: '로그인', exact: true }).click(); await page.waitForURL('**/#/?view=interest')
    ok('로그아웃·기존 로그인 화면 재로그인·관심 시작 화면')
    await go('/account/password')
    await page.locator('#pw-email').fill(email); await page.getByRole('button', { name: '이메일 확인' }).click()
    // Chrome may populate the native input without dispatching a React change event.
    await page.locator('#pw-current').evaluate((input, value) => { input.value = value }, password)
    await page.locator('#pw-next').fill('Changed!456'); await page.locator('#pw-confirm').fill('Changed!456')
    await page.getByRole('button', { name: '변경 저장' }).click(); await page.waitForURL('**/#/login')
    await page.locator('#login-email').fill(email); await page.locator('#login-password').fill(password); await page.getByRole('button', { name: '로그인', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: '일치하지 않습니다' }).waitFor()
    await page.locator('#login-password').fill('Changed!456'); await page.getByRole('button', { name: '로그인', exact: true }).click(); await page.waitForURL('**/#/?view=interest')
    ok('기존 비밀번호 변경 화면·세션 무효화·옛 비밀번호 거부·새 비밀번호 로그인')
    assert.equal(await page.evaluate(() => localStorage.getItem('bs2.accounts')), null)
    assert.deepEqual(errors, [])
    ok('브라우저 오류 없음·계정/비밀번호 localStorage 저장 없음')
    fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({ checks, errors }, null, 2))
    console.log(`${checks.length} integration checks passed`)
  } catch (error) {
    await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true })
    fs.writeFileSync(path.join(out, 'failure.txt'), await page.locator('body').innerText())
    fs.writeFileSync(path.join(out, 'errors.json'), JSON.stringify(errors)); throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
