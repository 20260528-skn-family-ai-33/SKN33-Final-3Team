// The real notification store, popover and inbox; no live API requests.
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const { chromium } = require('playwright')

;(async () => {
  const { createServer } = await import('vite')
  const server = await createServer({ root: path.resolve(__dirname, '..'), server: { host: '127.0.0.1', port: 0, proxy: {} } })
  await server.listen()
  let browser
  try {
    browser = await chromium.launch({ headless: true, args: ['--disable-features=LocalNetworkAccessChecks'], ...(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {}) })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    page.setDefaultTimeout(10000)
    const errors = [], mutations = []
    page.on('pageerror', e => errors.push(e.message))
    let account = '1'
    const titles = { '1': '월간 리포트가 발행되었습니다.', '2': '미국 수출 규제 관련 주요 이슈', '3': '반도체 관련 기사가 급증했습니다.', '4': 'EU 통상 정책 관련 주요 이슈', '5': '새로운 주요 이슈가 도착했습니다.' }
    const notice = id => ({ user_alert_id: id, event_type: id === '1' ? 'REPORT' : id === '3' ? 'SPIKE' : 'MAJOR_ISSUE', title: titles[id], message: `테스트 알림 본문 ${id}`, created_at: '2026-11-18T01:00:00Z', read_at: null })
    const notices = ['1', '2', '3', '4'].map(notice)
    await page.route('**/api/v1/**', route => {
      const req = route.request(), p = new URL(req.url()).pathname.replace('/api/v1', '')
      if (req.method() !== 'GET') mutations.push([req.method(), p])
      const reply = json => route.fulfill({ json })
      if (p === '/auth/login') account = '2'
      if (p === '/users/me' || p === '/auth/login') return reply({ user: { user_id: account, role: 'USER', name: '테스트', email: `user${account}@example.test` }, csrf_token: 'synthetic' })
      if (p === '/users/me/interests') return reply({ interests: { hs_items: [], country_codes: [], landing_page: 'GLOBAL' } })
      if (p === '/users/me/notification-settings') return reply({ settings: { notifications_enabled: true } })
      if (p === '/users/me/subscriptions') return reply({ items: [], version: '1' })
      if (p === '/config/options') return reply({ report_periods: [] })
      if (p === '/notifications') return reply({ items: notices, page: { has_next: false } })
      if (p === '/notifications/popups') return reply({ groups: [], retry_after_seconds: 30 })
      if (p === '/notifications/unread-count') return reply({ count: notices.filter(n => !n.read_at).length })
      if (/^\/notifications\/\d+\/read$/.test(p)) {
        notices.find(n => n.user_alert_id === p.split('/')[2]).read_at = '2026-11-18T02:00:00Z'
        return route.fulfill({ status: 204 })
      }
      if (['/reference/countries', '/reports', '/chat/sessions'].includes(p)) return reply({ items: [] })
      errors.push('Unexpected API: ' + p)
      return route.fulfill({ status: 500, json: {} })
    })
    await page.route('**/mini-alerts-harness', route => route.fulfill({ contentType: 'text/html', body: `
      <div id="root"></div><script type="module">
      import RefreshRuntime from '/@react-refresh'; RefreshRuntime.injectIntoGlobalHook(window);
      window.$RefreshReg$=()=>{}; window.$RefreshSig$=()=>type=>type;
      window.__vite_plugin_react_preamble_installed__=true;
      await import('/tests/mini-alerts-harness.jsx');</script>` }))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/mini-alerts-harness#/account/notifications`)
    const open = () => page.locator('button.bell').click()
    const dialog = page.getByRole('dialog', { name: '최근 알림' })
    const remove = id => dialog.getByRole('button', { name: `${titles[id]} 미니 알림 삭제` })
    const dir = path.resolve(__dirname, '../../tmp/issue135-review')
    fs.mkdirSync(dir, { recursive: true })
    const capturePopover = async name => {
      const box = await dialog.boundingBox()
      await page.screenshot({ path: path.join(dir, name), clip: { x: box.x - 12, y: 0, width: box.width + 36, height: Math.ceil(box.y + box.height + 16) } })
    }
    await open()
    await dialog.getByText('미확인 4건', { exact: true }).waitFor()
    assert.equal(await page.locator('button.bell').getAttribute('aria-label'), '알림 4건')
    await capturePopover('01-before-delete.png')
    const before = await page.getByTestId('original').textContent()
    await remove('1').click()
    await remove('1').waitFor({ state: 'detached' })
    assert.equal(await dialog.locator('.item').count(), 3) // next item fills the vacancy
    await dialog.getByText('미확인 3건', { exact: true }).waitFor()
    assert.equal(await page.locator('button.bell').getAttribute('aria-label'), '알림 3건')
    await capturePopover('02-after-one-delete.png')
    assert.equal(await page.getByTestId('original').textContent(), before)
    assert.equal(await page.getByTestId('unread').textContent(), '4')
    assert.deepEqual(mutations, [])
    await page.locator('.pop-dismiss').click({ position: { x: 5, y: 500 } })
    await open()
    assert.equal(await remove('1').count(), 0)
    await page.reload()
    await dialog.waitFor()
    await dialog.getByText('미확인 3건', { exact: true }).waitFor()
    assert.equal(await remove('1').count(), 0)
    await dialog.getByRole('button', { name: '모두 삭제' }).click()
    await dialog.getByText('새 알림이 없습니다.').waitFor()
    assert.equal(await page.locator('button.bell').getAttribute('aria-label'), '알림 0건')
    assert.equal(await page.locator('button.bell b').count(), 0)
    assert.equal(await dialog.getByText(/미확인 \d+건/).count(), 0)
    assert.equal(await page.getByTestId('original').textContent(), before)
    assert.equal(await page.getByTestId('unread').textContent(), '4')
    await capturePopover('03-after-delete-all.png')
    assert.deepEqual(mutations, [])
    await dialog.getByRole('button', { name: '알림함 전체 보기' }).click()
    for (const id of ['1', '2', '3', '4']) await page.getByText(titles[id], { exact: true }).waitFor()
    assert.equal(await page.getByRole('navigation', { name: '마이페이지 메뉴' }).getByRole('link', { name: /알림함/ }).locator('.n').innerText(), '4')
    await page.locator('main.page').screenshot({ path: path.join(dir, '04-full-inbox-preserved.png') })
    notices.unshift(notice('5'))
    await page.evaluate(() => window.miniAlertTest.refresh(true))
    await open()
    await remove('5').waitFor()
    assert.equal(await page.locator('button.bell').getAttribute('aria-label'), '알림 1건')
    await dialog.getByText('미확인 1건', { exact: true }).waitFor()
    assert.equal(await dialog.locator('.item').count(), 1)
    await dialog.getByRole('button', { name: '알림함 전체 보기' }).click()
    for (const id of ['1', '2', '3', '4', '5']) await page.getByText(titles[id], { exact: true }).waitFor()
    assert.equal(await page.getByTestId('unread').textContent(), '5')
    await page.evaluate(() => window.miniAlertTest.login('other@example.test', 'synthetic'))
    await open()
    await remove('1').waitFor() // same IDs in another account must not inherit hidden state
    assert.equal(await page.locator('button.bell').getAttribute('aria-label'), '알림 5건')
    await page.screenshot({ path: path.join(dir, 'alerts-desktop.png') })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: path.join(dir, 'alerts-mobile.png') })
    const box = await dialog.boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 844)
    await dialog.getByRole('button', { name: '모두 읽음' }).click()
    await page.waitForFunction(() => document.querySelector('[data-testid="unread"]').textContent === '0')
    assert.equal(await page.locator('button.bell b').count(), 0)
    assert.equal(mutations.filter(([method]) => method === 'PATCH').length, 5)
    await dialog.locator('.item').first().click()
    await page.getByText('알림 상세', { exact: true }).waitFor()
    assert.ok(page.url().includes('id=5'))
    assert.equal(mutations.some(([method]) => method === 'DELETE'), false)
    assert.deepEqual(errors, [])
    console.log('PASS visible-only popover/header badges, original inbox counts, individual/all dismissal, refresh/reopen, new notifications, account isolation, detail/read-all, mobile layout')
  } finally { if (browser) await browser.close(); await server.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
